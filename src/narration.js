          const g = actx.createGain();
          osc.type = 'sine';
          osc.frequency.setValueAtTime(180, actx.currentTime);
          osc.frequency.exponentialRampToValueAtTime(520, actx.currentTime + 2.4);
          g.gain.setValueAtTime(0.08 * vol, actx.currentTime);
          g.gain.exponentialRampToValueAtTime(0.001, actx.currentTime + 2.5);
          osc.connect(g);
          g.connect(actx.destination);
          osc.start();
          osc.stop(actx.currentTime + 2.55);

  renderParticles(ctx, scene, w, h) {
    ctx.save();
    const isDark = scene && (scene.id === 'scene3' || scene.id === 'scene4' || scene.id === 'scene5');
    for (let i = 0; i < this.particles.length; i++) {
      const p = this.particles[i];
      const sparkleAlpha = p.alpha * (0.5 + Math.sin(p.sparkle) * 0.4);
      ctx.globalAlpha = Math.max(0.08, Math.min(0.95, sparkleAlpha));
      ctx.fillStyle = isDark ? (i % 3 === 0 ? '#FF6B6B' : '#00F0FF') : '#FFD700';
      ctx.beginPath();
      ctx.arc(p.x % (w + 40), p.y, p.size, 0, Math.PI * 2);
      ctx.fill();
    }
    ctx.restore();
  }


  // Smooth directional camera wipe / atmospheric morph between two disaster environments (NEVER black!)
  renderDisaster_WithCrossSlide(ctx, w, h, fromKey, toKey, mix, t, nextTitle) {
    // Subtle directional pan or vertical tilt matching the environmental link!
    const isUpwardTilt = toKey === 'meteorological' || toKey === 'extraterrestrial' || toKey === 'orbital_sweep';
    const ease = this.easeInOutCubic(mix);

    ctx.save();
    // Background exiting environment shifting opposite direction
    ctx.save();
    ctx.translate(isUpwardTilt ? 0 : -ease * w * 0.28, isUpwardTilt ? ease * h * 0.28 : 0);
    this.drawSingleDisasterByKey(ctx, w, h, fromKey, t, 1.0);
    ctx.restore();

    // Incoming environment gliding & fading smoothly over top
    ctx.save();
    ctx.globalAlpha = ease;
    ctx.translate(isUpwardTilt ? 0 : (1 - ease) * w * 0.28, isUpwardTilt ? -(1 - ease) * h * 0.28 : 0);
    this.drawSingleDisasterByKey(ctx, w, h, toKey, t, mix * 0.4);
    ctx.restore();

    if (nextTitle && ease > 0.35) {
      const colorMap = {
        geophysical: '#FF6B35',
        hydrological: '#3498DB',
        meteorological: '#A29BFE',
        climatological: '#00D2D3',
        biological: '#2ED573',
        extraterrestrial: '#FF4757'
      };
      this.drawDisasterTitleOverlay(ctx, w, nextTitle, colorMap[toKey] || '#FFD700', mix);
    }
    ctx.restore();
  }


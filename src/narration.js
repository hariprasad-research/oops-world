  // CAMERA DIRECTOR PER SCENE (Seamless Visual Handshakes!)
  // -------------------------------------------------------------
  updateCameraForScene(scene, w, h) {
    const t = this.sceneTimer;
    this.camera.rot = 0;

    if (scene.id === 'scene1') {
      // Scene 1: Smooth dolly follow -> push into Magical Tree Root Crystal at end
      // Ending state: zoom = 1.38, x = -w * 0.14, y = -28 (Crystal at center-right)
      const zoomPush = this.smoothstep(21.4, 26.31, t);
      this.camera.zoom = this.lerp(1.0, 1.38, zoomPush);
      this.camera.x = this.lerp(Math.sin(t * 0.35) * 6, -w * 0.14, zoomPush);
      this.camera.y = this.lerp(0, -28, zoomPush);
    } else if (scene.id === 'scene2') {
      // Scene 2 starts cleanly on the EXACT final framing of Scene 1!
      const pushIn = this.smoothstep(0.0, 12.0, t);
      const awaken = this.smoothstep(12.0, 17.37, t);
      this.camera.zoom = this.lerp(1.38, 1.72, pushIn) + awaken * 0.14;
      this.camera.x = this.lerp(-w * 0.14, -w * 0.18, pushIn);
      this.camera.y = this.lerp(-28, -42, pushIn);
      if (t >= 12.0) {
        this.camera.trauma = Math.min(0.42, awaken * 0.44);
      }
    } else if (scene.id === 'scene3') {
      // Scene 3 starts on Scene 2's crystal close-up, follows beam UP into sky, then sweeps down over chaos!
      if (t < 3.15) {
        // 0.0 -> 0.4s explosion shock at crystal; 0.4 -> 3.15s camera shoots UP following beam!
        const beamClimb = this.easeInOutCubic((t - 0.35) / 2.6);
        this.camera.zoom = this.lerp(1.86, 1.05, beamClimb);
        this.camera.x = this.lerp(-w * 0.18, 0, beamClimb);
        this.camera.y = this.lerp(-42, 160, beamClimb); // shifts view skyward dynamically
        this.camera.trauma = Math.max(0.45, 0.92 - t * 0.15);
      } else {
        // Tilt back down over trembling valley & tidal surge
        const settle = this.smoothstep(3.15, 7.5, t);
        this.camera.y = this.lerp(160, 0, settle);
        this.camera.zoom = this.lerp(1.05, 1.0, settle);
        this.camera.trauma = t < 16.0 ? 0.38 : this.lerp(0.38, 0.06, this.smoothstep(16.0, 19.77, t));
        this.camera.x = Math.sin(t * 1.4) * 8;
      }
    } else if (scene.id === 'scene4') {
      // Continuous sweeping orbital / disaster camera
      const panLead = this.smoothstep(0, 4.3, t);
      this.camera.zoom = 1.03 + Math.sin(t * 0.8) * 0.03;
      this.camera.x = this.lerp(0, -18, panLead) + Math.sin(t * 0.6) * 10;
      this.camera.y = Math.cos(t * 0.7) * 5;
      // Tremors during Geophysical / Meteor phases
      if ((t >= 4.0 && t < 6.3) || (t >= 27.8 && t < 29.5)) {
        this.camera.trauma = 0.45;
      } else if ((t >= 15.5 && t < 19.1) || t >= 35.2) {
        this.camera.trauma = 0.25;
      } else {
        this.camera.trauma = 0.12;
      }
    } else if (scene.id === 'scene5') {
      // Push gently closer to rising Bobo
      const heroPush = this.smoothstep(15.6, 25.31, t);
      this.camera.zoom = this.lerp(1.0, 1.18, heroPush);
      this.camera.x = 0;
      this.camera.y = this.lerp(0, -18, heroPush);
    } else if (scene.id === 'scene6') {
      // High-energy tracking camera
      const finaleZoom = this.smoothstep(26.0, 32.0, t);
      this.camera.zoom = this.lerp(1.04, 1.24, finaleZoom);
      this.camera.x = 0;
      this.camera.y = 0;
    } else {
      this.camera.x = 0;
      this.camera.y = 0;
      this.camera.zoom = 1.0;
    }
  }

